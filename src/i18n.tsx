const translatableProps = ["aria-label", "title", "placeholder"] as const;

export function localizeDomTree(root: HTMLElement, language: Language) {
  if (language === "EN") return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let current = walker.nextNode();
  while (current) {
    if (current.textContent) current.textContent = translateToZh(current.textContent);
    current = walker.nextNode();
  }

  for (const element of root.querySelectorAll<HTMLElement>("[aria-label], [title], [placeholder]")) {
    for (const prop of translatableProps) {
      const value = element.getAttribute(prop);
      if (value) element.setAttribute(prop, translateToZh(value));
    }
  }
}

function translateToZh(value: string): string {
  if (!value.trim()) return value;
  const trimmed = value.trim();
  const trimmedExact = zhExact[trimmed];
  if (trimmedExact) {
    const leading = value.match(/^\s*/)?.[0] ?? "";
    const trailing = value.match(/\s*$/)?.[0] ?? "";
    return `${leading}${trimmedExact}${trailing}`;
  }
  const exact = zhExact[value];
  if (exact) return exact;
  let result = value;
  for (let pass = 0; pass < 2; pass += 1) {
    const before = result;
    for (const [pattern, replacement] of zhReplacements) {
      result = result.replace(pattern, replacement);
    }
    if (result === before) break;
  }
  return zhExact[result] ?? result;
}
